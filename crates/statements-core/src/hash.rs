//! Row ids compatible with the n8n "Enrich csv (id & unique descriptions)" node.
//!
//! n8n's `hashString` is the Java-style `hash * 31 + charCode` over UTF-16 code units, wrapped to i32.

/// How the date is rendered into the hash input.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum DateFormat {
    /// What the n8n code does: `date.toISOString()` on a midnight date with the server in UTC,
    /// e.g. `2026-06-01T00:00:00.000Z`.
    #[default]
    UtcTimestamp,
    /// The plain sheet date string, e.g. `2026-06-01`.
    SheetDate,
}

impl std::str::FromStr for DateFormat {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s {
            "utc" => Ok(Self::UtcTimestamp),
            "date" => Ok(Self::SheetDate),
            other => Err(format!(
                "unknown hash date format '{other}' (expected 'utc' or 'date')"
            )),
        }
    }
}

/// Port of n8n's `hashString`: `hash = ((hash << 5) - hash) + str.charCodeAt(i); hash |= 0;`
pub fn hash_string(s: &str) -> i32 {
    s.encode_utf16().fold(0i32, |hash, unit| {
        hash.wrapping_shl(5)
            .wrapping_sub(hash)
            .wrapping_add(i32::from(unit))
    })
}

/// The string that gets hashed for a row. `date` is `YYYY-MM-DD`; `amount` is the raw CSV string.
pub fn hash_input(date: &str, description: &str, amount: &str, format: DateFormat) -> String {
    match format {
        DateFormat::UtcTimestamp => format!("{date}T00:00:00.000Z-{description}-{amount}"),
        DateFormat::SheetDate => format!("{date}-{description}-{amount}"),
    }
}

/// Row id as n8n computes it. `date` is `YYYY-MM-DD`; `amount` is the raw CSV string.
pub fn row_id(date: &str, description: &str, amount: &str, format: DateFormat) -> i32 {
    hash_string(&hash_input(date, description, amount, format))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// (date, description, amount, utc id, sheet-date id), generated by running the n8n JS
    /// verbatim under Node with TZ=UTC.
    const N8N_JS_VECTORS: &[(&str, &str, &str, i32, i32)] = &[
        (
            "2027-12-29",
            "IB PAYMENT TO EXAMPLE MUNICIPALITY ACC 001",
            "-250.75",
            -2113598457,
            -1348798325,
        ),
        // Trailing space from an empty col5.
        (
            "2027-12-31",
            "FIXED MONTHLY FEE ",
            "-120",
            -1406063539,
            1671829129,
        ),
        // Duplicate-suffixed description.
        (
            "2027-12-31",
            "OVERDRAFT SERVICE FEE _",
            "-57.5",
            620216679,
            1300958883,
        ),
        // Runs of spaces; negative id.
        (
            "2028-02-01",
            "REGISTERED DC DEBIT HOME LOAN DC   0000001       280201",
            "-899.99",
            -1690909981,
            1748560479,
        ),
        // Non-ASCII, including a surrogate pair (emoji = two UTF-16 units).
        (
            "2026-12-31",
            "Café ☕ 😀",
            "1,234.00",
            435566368,
            -835488476,
        ),
    ];

    #[test]
    fn matches_n8n_js_utc_timestamp() {
        for &(date, desc, amount, utc, _) in N8N_JS_VECTORS {
            assert_eq!(
                row_id(date, desc, amount, DateFormat::UtcTimestamp),
                utc,
                "{date} {desc:?}"
            );
        }
    }

    #[test]
    fn matches_n8n_js_sheet_date() {
        for &(date, desc, amount, _, plain) in N8N_JS_VECTORS {
            assert_eq!(
                row_id(date, desc, amount, DateFormat::SheetDate),
                plain,
                "{date} {desc:?}"
            );
        }
    }

    #[test]
    fn empty_string_hashes_to_zero() {
        assert_eq!(hash_string(""), 0);
    }

    #[test]
    fn parses_cli_values() {
        assert_eq!("utc".parse(), Ok(DateFormat::UtcTimestamp));
        assert_eq!("date".parse(), Ok(DateFormat::SheetDate));
        assert!("other".parse::<DateFormat>().is_err());
    }
}
